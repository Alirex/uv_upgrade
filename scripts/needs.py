"""needs.py: read a repo's needs.yaml (what it needs to run, develop, test, build in CI and release).

Usage: scripts/needs.py [-h] {check,render,lint,ci} [--root DIR] ...
       check --context C [--part P] [--network] [--json]   this machine against the file; exit 1 on a MISS
       render [--check] [--setup-check FILE]               write or verify the generated README table and setup-check
       lint                                                schema, vocabularies, pins, `why`; exit 1 on a problem
       ci                                                  workflows against the declared `ci` needs; exit 1 on mismatch
Convention: HQ practices/needs-by-context.md. This file is vendored into every registry repo as scripts/needs.py
(HQ's copy is scripts/repos/needs.py; `just practices-sync` copies it, `just repos-conformance` compares the copies).
It is deliberately self-contained (standard library and pyyaml, no HQ import) so it runs on a GitHub-hosted runner;
for the same reason it uses argparse and not Typer, which HQ's other scripts use.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tomllib
import urllib.request
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Final, cast

import yaml

NEEDS_FILE: Final[str] = "needs.yaml"
CONTEXTS: Final[tuple[str, ...]] = ("run", "develop", "test", "ci", "release")
KINDS: Final[tuple[str, ...]] = ("tool", "package", "hardware", "service", "network", "env", "data")
LEVELS: Final[tuple[str, ...]] = ("required", "optional")
OSES: Final[tuple[str, ...]] = ("linux", "macos", "windows")
WHY_MAX: Final[int] = 110
COMMON_KEYS: Final[frozenset[str]] = frozenset(
    {"kind", "name", "contexts", "part", "level", "why", "fallback", "check", "fix", "os"},
)
KIND_KEYS: Final[dict[str, frozenset[str]]] = {
    "tool": frozenset({"pinned_by", "min"}),
    "package": frozenset({"apt", "brew", "dnf"}),
    "hardware": frozenset({"protocols", "virtual_ok", "api", "software_ok"}),
    "service": frozenset({"provided_by", "version"}),
    "network": frozenset({"hosts", "login"}),
    "env": frozenset({"names", "secret", "example"}),
    "data": frozenset({"path", "url", "fetched_by"}),
}
KIND_CHECKS: Final[dict[str, tuple[str, ...]]] = {
    "tool": ("command", "none"),
    "package": ("package", "none"),
    "hardware": ("display", "gpu", "none"),
    "service": ("docker", "service", "none"),
    "network": ("url", "none"),
    "env": ("env", "none"),
    "data": ("file", "none"),
}
NAMED_KINDS: Final[frozenset[str]] = frozenset({"tool", "hardware", "service", "data"})
HARDWARE_NAMES: Final[tuple[str, ...]] = ("display", "gpu", "memory", "disk")
ENV_NAME: Final[re.Pattern[str]] = re.compile(r"[A-Z][A-Z0-9_]*")
VERSION: Final[re.Pattern[str]] = re.compile(r"\d+(?:\.\d+)*")
README_BEGIN: Final[str] = "<!-- needs:begin (generated by scripts/needs.py render; do not edit) -->"
README_END: Final[str] = "<!-- needs:end -->"
SETUP_BEGIN: Final[str] = "# [needs]-[BEGIN] (generated by scripts/needs.py render; do not edit)"
SETUP_END: Final[str] = "# [needs]-[END]"
SETUP_CHECK_FILES: Final[tuple[str, ...]] = ("scripts/setup/setup-check.sh", "scripts/setup-check.sh")
SHELL_STOP: Final[frozenset[str]] = frozenset({"&&", "||", ";", "|", "&", ">", ">>", "2>&1"})
APT_INSTALL: Final[re.Pattern[str]] = re.compile(r"\bapt(?:-get)?\s+(?:-\S+\s+)*install\b(.*)")

Raw = dict[str, object]


def current_os() -> str:
    """Return linux, macos or windows."""
    return {"darwin": "macos", "win32": "windows"}.get(sys.platform, "linux")


def as_dict(value: object) -> Raw:
    """Return the value as a mapping, or an empty one."""
    return cast("Raw", value) if isinstance(value, dict) else {}


def as_list(value: object) -> list[object]:
    """Return the value as a list, or an empty one."""
    return cast("list[object]", value) if isinstance(value, list) else []


def text_of(raw: Raw, key: str) -> str:
    """Return a scalar key as text ("" when absent)."""
    value = raw.get(key)
    return "" if value is None or isinstance(value, (dict, list)) else str(value)


def strings_of(raw: Raw, key: str) -> tuple[str, ...]:
    """Return a list key as a tuple of text."""
    return tuple(str(item) for item in as_list(raw.get(key)))


@dataclass(frozen=True)
class Need:
    """One entry of needs.yaml, read from a mapping that lint accepted."""

    kind: str
    name: str
    contexts: tuple[str, ...]
    level: str
    why: str
    check: str
    part: str = ""
    fallback: str = ""
    fix: str = ""
    oses: tuple[str, ...] = ()
    pinned_by: str = ""
    minimum: str = ""
    apt: tuple[str, ...] = ()
    brew: tuple[str, ...] = ()
    dnf: tuple[str, ...] = ()
    virtual_ok: bool = False
    api: str = ""
    software_ok: bool = False
    provided_by: str = ""
    hosts: tuple[str, ...] = ()
    names: tuple[str, ...] = ()
    path: str = ""
    fetched_by: str = ""

    @classmethod
    def from_raw(cls, raw: Raw) -> Need:
        """Build a need from a mapping."""
        return cls(
            kind=text_of(raw, "kind"),
            name=text_of(raw, "name"),
            contexts=strings_of(raw, "contexts"),
            level=text_of(raw, "level"),
            why=text_of(raw, "why"),
            check=text_of(raw, "check"),
            part=text_of(raw, "part"),
            fallback=text_of(raw, "fallback"),
            fix=text_of(raw, "fix"),
            oses=strings_of(raw, "os"),
            pinned_by=text_of(raw, "pinned_by"),
            minimum=text_of(raw, "min"),
            apt=strings_of(raw, "apt"),
            brew=strings_of(raw, "brew"),
            dnf=strings_of(raw, "dnf"),
            virtual_ok=raw.get("virtual_ok") is True,
            api=text_of(raw, "api"),
            software_ok=raw.get("software_ok") is True,
            provided_by=text_of(raw, "provided_by"),
            hosts=strings_of(raw, "hosts"),
            names=strings_of(raw, "names"),
            path=text_of(raw, "path"),
            fetched_by=text_of(raw, "fetched_by"),
        )

    @property
    def label(self) -> str:
        """A short name: the name, else the packages, hosts or variables."""
        for value in (
            self.name,
            ",".join(self.apt or self.brew or self.dnf),
            ",".join(self.hosts),
            ",".join(self.names),
        ):
            if value:
                return value
        return self.kind


# --- loading and lint -------------------------------------------------------------------------------------------


def load_raw(root: Path) -> tuple[list[Raw], list[str]]:
    """Return the raw needs and the problems that stop the file from being read at all."""
    try:
        data = cast("object", yaml.safe_load((root / NEEDS_FILE).read_text(encoding="utf-8")))
    except OSError:
        return [], [f"{NEEDS_FILE}: not found in {root}"]
    except yaml.YAMLError as error:
        return [], [f"{NEEDS_FILE}: invalid YAML: {error}"]
    top = as_dict(data)
    if not top:
        return [], [f"{NEEDS_FILE}: must be a mapping with `version` and `needs`"]
    problems = [] if top.get("version") == 1 else [f"{NEEDS_FILE}: `version` must be 1"]
    items = as_list(top.get("needs"))
    if not isinstance(top.get("needs"), list):
        return [], [*problems, f"{NEEDS_FILE}: `needs` must be a list"]
    if not all(isinstance(item, dict) for item in items):
        return [], [*problems, f"{NEEDS_FILE}: every entry of `needs` must be a mapping"]
    return [as_dict(item) for item in items], problems


def load_needs(root: Path) -> tuple[list[Need], list[str]]:
    """Return the needs of a repo whose file lints clean, else no needs and the problems."""
    raws, problems = load_raw(root)
    problems += [p for index, raw in enumerate(raws) for p in lint_need(index, raw, root)]
    return ([] if problems else [Need.from_raw(raw) for raw in raws]), problems


def split_pin(spec: str) -> tuple[str, str]:
    """Split `file#key.path` into the file and the key path (empty when there is none)."""
    file, _, key = spec.partition("#")
    return file, key


def read_pin(root: Path, spec: str) -> str | None:
    """Return the version a native pin file holds, or None when the file or the key is missing."""
    file, key = split_pin(spec)
    path = root / file
    try:
        content = path.read_text(encoding="utf-8")
    except OSError:
        return None
    if path.name == "rust-toolchain.toml" and not key:
        key = "toolchain.channel"
    value: object
    if path.suffix in {".toml", ".json"}:
        try:
            value = tomllib.loads(content) if path.suffix == ".toml" else json.loads(content)
        except ValueError:  # TOMLDecodeError and JSONDecodeError are both ValueErrors
            return None
        for part in filter(None, key.split(".")):
            value = as_dict(value).get(part)
    else:
        lines = [line.strip() for line in content.splitlines() if line.strip() and not line.startswith("#")]
        value = lines[0] if lines else None
    return None if value is None or isinstance(value, (dict, list)) or str(value) == "" else str(value)


def is_strings(value: object) -> bool:
    """Whether the value is a non-empty list of strings."""
    items = as_list(value)
    return bool(items) and all(isinstance(item, str) for item in items)


def lint_need(index: int, raw: Raw, root: Path) -> list[str]:
    """Return the problems of one need."""
    need = Need.from_raw(raw)
    name = f"needs[{index}] ({need.label})"
    kind = need.kind
    if kind not in KINDS:
        return [f"{name}: `kind` must be one of {', '.join(KINDS)}"]
    problems = [
        f"{name}: unknown key `{key}` for kind {kind}" for key in sorted(set(raw) - COMMON_KEYS - KIND_KEYS[kind])
    ]
    if not need.contexts or any(c not in CONTEXTS for c in need.contexts) or not is_strings(raw.get("contexts")):
        problems.append(f"{name}: `contexts` must be a non-empty list from {', '.join(CONTEXTS)}")
    if need.level not in LEVELS:
        problems.append(f"{name}: `level` must be required or optional")
    elif need.level == "optional" and not need.fallback:
        problems.append(f"{name}: an optional need needs a `fallback` (what happens without it)")
    if not need.why.strip():
        problems.append(f"{name}: `why` is required (one line)")
    elif len(need.why) > WHY_MAX or "\n" in need.why.strip():
        problems.append(f"{name}: `why` must be one line of at most {WHY_MAX} characters")
    if "os" in raw and (not is_strings(raw["os"]) or any(o not in OSES for o in need.oses)):
        problems.append(f"{name}: `os` must be a list from {', '.join(OSES)}")
    if need.check not in KIND_CHECKS[kind]:
        problems.append(f"{name}: `check` for kind {kind} must be one of {', '.join(KIND_CHECKS[kind])}")
    if kind in NAMED_KINDS and not need.name:
        problems.append(f"{name}: `name` is required for kind {kind}")
    return problems + lint_kind(name, raw, need, root)


def lint_kind(name: str, raw: Raw, need: Need, root: Path) -> list[str]:  # noqa: C901, PLR0912  # one branch per kind
    """Return the problems that depend on the kind of a need."""
    problems: list[str] = []
    kind = need.kind
    if kind == "tool" and need.pinned_by:
        if need.minimum:
            problems.append(f"{name}: `min` is forbidden when `pinned_by` names the version")
        if read_pin(root, need.pinned_by) is None:
            problems.append(f"{name}: `pinned_by` {need.pinned_by!r} is missing or yields no version")
    elif kind == "package":
        listed = [key for key in ("apt", "brew", "dnf") if raw.get(key)]
        if not listed:
            problems.append(f"{name}: a package need lists packages under `apt`, `brew` or `dnf`")
        problems += [f"{name}: `{key}` must be a list of strings" for key in listed if not is_strings(raw[key])]
    elif kind == "hardware":
        if need.name not in HARDWARE_NAMES:
            problems.append(f"{name}: hardware `name` must be one of {', '.join(HARDWARE_NAMES)}")
        elif need.check in {"display", "gpu"} and need.check != need.name:
            problems.append(f"{name}: `check: {need.check}` needs `name: {need.check}`")
    elif kind == "service":
        if need.check == "service" and not need.provided_by:
            problems.append(f"{name}: `check: service` needs `provided_by`")
    elif kind == "network":
        if not is_strings(raw.get("hosts")):
            problems.append(f"{name}: `hosts` must be a list of host names")
    elif kind == "env":
        if not is_strings(raw.get("names")) or any(not ENV_NAME.fullmatch(n) for n in need.names):
            problems.append(f"{name}: `names` must be a list of UPPER_CASE variable names (never a value)")
    elif kind == "data" and need.check == "file" and not need.path:
        problems.append(f"{name}: `check: file` needs `path`")
    return problems


def lint(root: Path) -> list[str]:
    """Return every problem of the repo's needs.yaml."""
    return load_needs(root)[1]


# --- check ------------------------------------------------------------------------------------------------------


@dataclass(frozen=True)
class Row:
    """One need checked on this machine."""

    state: str
    name: str
    kind: str
    level: str
    part: str
    detail: str


def run_quiet(argv: list[str], timeout: float = 5) -> str | None:
    """Return the output of a command, or None when it fails, is missing or times out."""
    try:
        done = subprocess.run(argv, capture_output=True, text=True, timeout=timeout, check=False)
    except OSError:
        return None
    except subprocess.SubprocessError:
        return None
    return (done.stdout + done.stderr) if done.returncode == 0 else None


def version_tuple(content: str) -> tuple[int, ...] | None:
    """Return the first dotted version in the text."""
    match = VERSION.search(content)
    return tuple(int(p) for p in match.group(0).split(".")) if match else None


def check_command(need: Need, root: Path) -> tuple[bool, str]:
    """Return (found, detail) for a tool on PATH, with the pin or minimum it is held to."""
    if shutil.which(need.name) is None:
        return False, need.fix or f"install {need.name}"
    output = run_quiet([need.name, "--version"]) or ""
    shown = " ".join(output.split("\n", 1)[0].split()[:4]) or "found"
    pin = read_pin(root, need.pinned_by) if need.pinned_by else None
    minimum = version_tuple(need.minimum)
    found = version_tuple(output)
    if minimum and found and found < minimum:
        return False, f"{shown}: needs at least {need.minimum}"
    return True, f"{shown} (pinned {pin} by {split_pin(need.pinned_by)[0]})" if pin else shown


def check_package(need: Need) -> tuple[bool | None, str]:
    """Return (found, detail) for system packages through the package manager this machine has."""
    probes = (
        ("apt", need.apt, ["dpkg", "-s"]),
        ("brew", need.brew, ["brew", "list"]),
        ("dnf", need.dnf, ["rpm", "-q"]),
    )
    for manager, packages, argv in probes:
        if packages and shutil.which(argv[0]):
            missing = [p for p in packages if run_quiet([*argv, p]) is None]
            return (not missing), (f"missing {', '.join(missing)} ({manager})" if missing else f"{manager}: installed")
    return None, "no package manager for the listed packages here"


def check_display(need: Need) -> tuple[str, str]:
    """Return (state, detail): a Wayland or X11 session, a virtual display, or nothing."""
    if current_os() != "linux" or os.environ.get("WAYLAND_DISPLAY") or os.environ.get("DISPLAY"):
        return "ok", "display session"
    if need.virtual_ok and shutil.which("xvfb-run"):
        return "virt", "no display; run under xvfb-run"
    return "MISS", "no WAYLAND_DISPLAY or DISPLAY" + (" and no xvfb-run" if need.virtual_ok else "")


def check_gpu(need: Need) -> tuple[str, str]:
    """Return (state, detail) for a GPU: a render node, nvidia-smi for cuda, else software if allowed."""
    if need.api == "cuda":
        found = shutil.which("nvidia-smi") is not None and run_quiet(["nvidia-smi", "-L"]) is not None
    else:
        found = any(Path("/dev/dri").glob("renderD*")) if Path("/dev/dri").is_dir() else current_os() != "linux"
    if found:
        return "ok", f"{need.api or 'gpu'} available"
    return ("soft", "no GPU; software rendering") if need.software_ok else ("MISS", "no GPU found")


def check_docker() -> tuple[bool, str]:
    """Return (running, detail) from `docker info`."""
    if shutil.which("docker") is None:
        return False, "docker is not installed"
    if run_quiet(["docker", "info"], timeout=3) is None:
        return False, "docker daemon does not answer"
    return True, "docker daemon answers"


def check_service(need: Need) -> tuple[bool, str]:
    """Return (ok, detail): the env var named by `provided_by`, or a throwaway container Docker can start."""
    provided = need.provided_by
    if provided.startswith("env:") and os.environ.get(provided[4:]):
        return True, f"{provided[4:]} is set"
    if provided in {"throwaway-container", "compose"}:
        running, detail = check_docker()
        return running, ("will start a container" if running else detail)
    return False, f"set {provided[4:]}" if provided.startswith("env:") else "not provided"


def check_url(need: Need) -> tuple[bool, str]:
    """Return (reachable, detail) for the first host of a network need (only with --network)."""
    for host in need.hosts[:1]:
        url = host if "://" in host else f"https://{host}"
        try:
            with urllib.request.urlopen(urllib.request.Request(url, method="HEAD"), timeout=5):  # noqa: S310
                return True, f"{host} reachable"
        except OSError:
            return False, f"{host} not reachable"
    return True, "no host"


def evaluate(need: Need, root: Path, *, network: bool) -> tuple[str, str]:  # noqa: C901  # one branch per check
    """Return (state, detail) of one need on this machine, ignoring its level."""
    result: tuple[bool | str | None, str]
    if need.check == "command":
        result = check_command(need, root)
    elif need.check == "package":
        result = check_package(need)
    elif need.check == "display":
        result = check_display(need)
    elif need.check == "gpu":
        result = check_gpu(need)
    elif need.check == "docker":
        result = check_docker()
    elif need.check == "service":
        result = check_service(need)
    elif need.check == "env":
        unset = [n for n in need.names if not os.environ.get(n)]
        result = (not unset), ("set" if not unset else f"unset: {', '.join(unset)}")
    elif need.check == "file":
        result = Path(need.path).expanduser().exists() or (root / need.path).exists(), need.path
    elif need.check == "url" and network:
        result = check_url(need)
    else:
        return "skip", "not checked"
    ok, detail = result
    if ok is None:
        return "n.a.", detail
    if isinstance(ok, str):
        return ok, detail
    return ("ok" if ok else "MISS"), detail


def check_needs(needs: list[Need], root: Path, context: str, part: str = "", *, network: bool = False) -> list[Row]:
    """Check every need of the context on this machine; an optional need that is missing reads `opt`."""
    rows: list[Row] = []
    for need in needs:
        if context not in need.contexts or (part and need.part and need.part != part):
            continue
        if need.oses and current_os() not in need.oses:
            state, detail = "n.a.", f"only on {', '.join(need.oses)}"
        else:
            state, detail = evaluate(need, root, network=network)
            if state == "MISS" and need.level == "optional":
                state, detail = "opt", f"{detail}; fallback: {need.fallback}"
        rows.append(Row(state, need.label, need.kind, need.level, need.part, f"{detail}  [{need.why}]"))
    return rows


# --- render -----------------------------------------------------------------------------------------------------


def cell(content: str) -> str:
    """Escape a Markdown table cell."""
    return content.replace("|", "\\|").replace("\n", " ")


def render_readme_table(needs: list[Need]) -> str:
    """Return the Markdown table of the needs."""
    lines = ["| Need | Contexts | Level | Why |", "| --- | --- | --- | --- |"]
    for need in needs:
        part = f" ({need.part})" if need.part else ""
        where = f" [{', '.join(need.oses)}]" if need.oses else ""
        lines.append(
            f"| `{cell(need.label)}` ({need.kind}) | {', '.join(need.contexts)}{part}{where} "
            f"| {need.level} | {cell(need.why)} |",
        )
    return "\n".join(lines)


def shell_quote(content: str) -> str:
    """Quote text for double quotes in bash."""
    return '"' + re.sub(r'(["\\$`])', r"\\\1", content) + '"'


def render_setup_check(needs: list[Need]) -> str:
    """Return the `tool need|want` lines for the tools of the develop context."""
    lines: list[str] = []
    for need in needs:
        if need.kind != "tool" or "develop" not in need.contexts or need.check != "command":
            continue
        if need.oses and not {"linux", "macos"} & set(need.oses):
            continue
        level = "need" if need.level == "required" else "want"
        lines.append(f"tool {level} {need.name} {shell_quote(need.fix or 'install ' + need.name)}")
    return "\n".join(lines)


def replace_block(content: str, begin: str, end: str, body: str) -> str | None:
    """Return the text with the block between the marker lines replaced, or None when a marker is missing."""
    prefix = begin.split(" (generated", 1)[0]
    lines = content.split("\n")
    first = next((i for i, line in enumerate(lines) if line.strip().startswith(prefix)), None)
    last = next((i for i, line in enumerate(lines) if line.strip() == end), None)
    if first is None or last is None or last < first:
        return None
    return "\n".join([*lines[: first + 1], *([body] if body else []), *lines[last:]])


def render(root: Path, needs: list[Need], setup_check: str, *, write: bool) -> list[tuple[str, str]]:
    """Return (file, state) per generated target: current, stale, updated, no-block or absent."""
    out: list[tuple[str, str]] = []
    targets = [(root / "README.md", README_BEGIN, README_END, render_readme_table(needs), True)]
    script = next((root / n for n in (setup_check,) if n and (root / n).is_file()), None)
    if not setup_check:
        script = next((root / n for n in SETUP_CHECK_FILES if (root / n).is_file()), None)
    if script:
        targets.append((script, SETUP_BEGIN, SETUP_END, render_setup_check(needs), False))
    for path, begin, end, body, required in targets:
        name = path.relative_to(root).as_posix()
        if not path.is_file():
            out.append((name, "absent"))
            continue
        old = path.read_text(encoding="utf-8")
        new = replace_block(old, begin, end, body)
        if new is None and write and required:
            intro = "## Needs\n\nGenerated from `needs.yaml` (`scripts/needs.py render`).\n"
            new = f"{old.rstrip(chr(10))}\n\n{intro}\n{begin}\n{body}\n{end}\n"
        if new is None:
            out.append((name, "no-block"))
        elif new == old:
            out.append((name, "current"))
        elif write:
            _ = path.write_text(new, encoding="utf-8")
            out.append((name, "updated"))
        else:
            out.append((name, "stale"))
    return out


def generated_problems(root: Path) -> list[str]:
    """Return what is wrong with the generated blocks: a missing README block, or a stale block."""
    needs, problems = load_needs(root)
    if problems:
        return problems
    found = render(root, needs, "", write=False)
    return [
        f"{name}: {state} (run scripts/needs.py render)"
        for name, state in found
        if (name == "README.md" and state != "current") or state == "stale"
    ]


# --- ci ---------------------------------------------------------------------------------------------------------


def workflow_runs(root: Path) -> list[str] | None:
    """Return every `run:` script of the active workflows, or None when the repo has no active workflow."""
    folder = root / ".github" / "workflows"
    files = sorted([*folder.glob("*.yml"), *folder.glob("*.yaml")])
    if not files:
        return None
    runs: list[str] = []
    for file in files:
        try:
            data = cast("object", yaml.safe_load(file.read_text(encoding="utf-8")))
        except OSError:
            continue
        except yaml.YAMLError:
            continue
        for job in as_dict(as_dict(data).get("jobs")).values():
            for step in as_list(as_dict(job).get("steps")):
                run = as_dict(step).get("run")
                if isinstance(run, str):
                    runs.append(run)
    return runs


def apt_packages(runs: list[str]) -> set[str]:
    """Return the package names installed by apt or apt-get in the scripts (variables and flags are skipped)."""
    found: set[str] = set()
    for script in runs:
        for line in script.replace("\\\n", " ").splitlines():
            match = APT_INSTALL.search(line)
            for token in match.group(1).split() if match else []:
                if token in SHELL_STOP or token.startswith("#"):
                    break
                if not token.startswith("-") and "$" not in token:
                    found.add(token)
    return found


def ci_problems(root: Path, needs: list[Need]) -> list[str] | None:
    """Return how the workflows differ from the `ci` needs, or None when there is no active workflow."""
    runs = workflow_runs(root)
    if runs is None:
        return None
    ci = [n for n in needs if "ci" in n.contexts and (not n.oses or "linux" in n.oses)]
    declared = {p for n in ci if n.kind == "package" for p in n.apt}
    used = apt_packages(runs)
    script = "\n".join(runs)
    problems = [
        f"workflow installs {p} with apt but needs.yaml does not declare it for ci" for p in sorted(used - declared)
    ]
    problems += [f"needs.yaml declares apt {p} for ci but no workflow installs it" for p in sorted(declared - used)]
    wants_xvfb = any(n.kind == "hardware" and n.name == "display" and n.virtual_ok for n in ci)
    if wants_xvfb != ("xvfb-run" in script):
        problems.append(
            "xvfb-run: "
            + (
                "declared (display with virtual_ok) but no workflow uses it"
                if wants_xvfb
                else "used but no ci display need has virtual_ok"
            ),
        )
    wants_browser = any("playwright install" in n.fetched_by for n in ci)
    if wants_browser != ("playwright install" in script):
        problems.append(
            "playwright install: "
            + (
                "declared (fetched_by) but no workflow runs it"
                if wants_browser
                else "run in a workflow but no ci need names it in fetched_by"
            ),
        )
    return problems


# --- command line -----------------------------------------------------------------------------------------------


class Args(argparse.Namespace):
    """The parsed command line, typed."""

    command: str = ""
    root: Path = Path()
    context: str = ""
    part: str = ""
    network: bool = False
    json: bool = False
    check: bool = False
    setup_check: str = ""


def command_check(args: Args) -> int:
    """Run `check`."""
    needs, problems = load_needs(args.root)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 2
    rows = check_needs(needs, args.root, args.context, args.part, network=args.network)
    if args.json:
        print(json.dumps([asdict(row) for row in rows], indent=2))
    else:
        print(f"== needs: context {args.context}{' part ' + args.part if args.part else ''} ({args.root})")
        for row in rows:
            print(f"{row.state:5} {row.name}{' (' + row.part + ')' if row.part else ''} - {row.detail}")
        misses = sum(1 for row in rows if row.state == "MISS")
        print(f"{len(rows)} needs, {misses} missing" if rows else f"no needs declared for {args.context}")
    return 1 if any(row.state == "MISS" for row in rows) else 0


def command_render(args: Args) -> int:
    """Run `render`."""
    needs, problems = load_needs(args.root)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 2
    if args.check:
        bad = generated_problems(args.root)
        print("\n".join(bad) if bad else "generated blocks are current")
        return 1 if bad else 0
    for name, state in render(args.root, needs, args.setup_check, write=True):
        print(f"{state:8} {name}")
    return 0


def command_lint(args: Args) -> int:
    """Run `lint`."""
    problems = lint(args.root)
    print("\n".join(problems) if problems else f"{NEEDS_FILE}: ok")
    return 1 if problems else 0


def command_ci(args: Args) -> int:
    """Run `ci`."""
    needs, problems = load_needs(args.root)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 2
    found = ci_problems(args.root, needs)
    if found is None:
        print("n.a.: no active workflow in .github/workflows")
        return 0
    print("\n".join(found) if found else "workflows match the ci needs")
    return 1 if found else 0


def build_parser() -> argparse.ArgumentParser:
    """Build the command line."""
    parser = argparse.ArgumentParser(prog="needs.py", description=(__doc__ or "").split("\n", maxsplit=1)[0])
    common = argparse.ArgumentParser(add_help=False)
    _ = common.add_argument(
        "--root", type=Path, default=Path.cwd(), help="the repo folder (default: the current directory)"
    )
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser("check", parents=[common], help="check this machine against the needs of one context")
    _ = check.add_argument("--context", required=True, choices=CONTEXTS)
    _ = check.add_argument("--part", default="", help="only needs of this part (and needs without a part)")
    _ = check.add_argument("--network", action="store_true", help="also probe network hosts")
    _ = check.add_argument("--json", action="store_true")
    rend = sub.add_parser("render", parents=[common], help="write or verify the README table and setup-check block")
    _ = rend.add_argument("--check", action="store_true", help="verify only; exit 1 when a block is stale or missing")
    _ = rend.add_argument(
        "--setup-check", default="", help="setup-check script (default: scripts/setup/setup-check.sh)"
    )
    _ = sub.add_parser("lint", parents=[common], help="validate needs.yaml")
    _ = sub.add_parser("ci", parents=[common], help="compare the workflows with the ci needs")
    return parser


def main(argv: list[str] | None = None) -> int:
    """Run the command line and return its exit code."""
    args = build_parser().parse_args(argv, namespace=Args())
    args.root = args.root.resolve()
    commands = {"check": command_check, "render": command_render, "lint": command_lint, "ci": command_ci}
    return commands[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
